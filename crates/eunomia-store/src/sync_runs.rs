// ---- Vocabularies -------------------------------------------------------------

/// The closed `sync_runs.status` vocabulary (the §6.2 CHECK): the
/// lifecycle of one run from its start to its final verdict.
///
/// Phase 0 writes exactly [`SyncRunStatus::Running`]; the final
/// members are §9.4 phase 4's verdicts (`success`/`partial`/`failed`)
/// plus the two mid-pipeline aborts (`aborted`, the phase-2 backup
/// stop) and the crash-recovery verdict (`interrupted`, written at
/// startup over a `running` row whose process died). The store
/// carries the whole vocabulary so the future phase writers and the
/// history reads share one owner; nothing here transitions a status
/// itself.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum SyncRunStatus {
    /// The run has started and not finished (phase 0's own value).
    Running,
    /// Every active project got `written` or `unchanged`.
    Success,
    /// At least one `skipped`/`failed` and at least one
    /// `written`/`unchanged`.
    Partial,
    /// The pipeline stopped before writing (phase 1's `E_DISK_FULL`
    /// tail rule, phase 2's `E_BACKUP_FAILED`).
    Aborted,
    /// No project was written or left unchanged.
    Failed,
    /// A `running` row whose process died — the startup recovery
    /// verdict.
    Interrupted,
}

impl SyncRunStatus {
    /// Every member, in the §6.2 CHECK's declaration order — the
    /// round-trip oracle of the vocabulary tests.
    pub const ALL: [SyncRunStatus; 6] = [
        SyncRunStatus::Running,
        SyncRunStatus::Success,
        SyncRunStatus::Partial,
        SyncRunStatus::Aborted,
        SyncRunStatus::Failed,
        SyncRunStatus::Interrupted,
    ];

    /// The stored TEXT literal (the §6.2 CHECK member).
    pub const fn as_str(&self) -> &'static str {
        match self {
            SyncRunStatus::Running => "running",
            SyncRunStatus::Success => "success",
            SyncRunStatus::Partial => "partial",
            SyncRunStatus::Aborted => "aborted",
            SyncRunStatus::Failed => "failed",
            SyncRunStatus::Interrupted => "interrupted",
        }
    }

    /// Decodes a stored (or wire) literal. Public for the same reason
    /// [`crate::action_log::Action::from_member`] is: the future IPC
    /// layer parses its status strings through this same decoder, so
    /// the vocabulary has one owner.
    ///
    /// # Errors
    ///
    /// Returns [`SyncRunsError::Member`] when `member` is none of the
    /// CHECK's literals — a cell only a newer app version or tampering
    /// can hold (the D-039 corrupt-cells policy: surface it, never
    /// guess around it).
    pub fn from_member(member: &str) -> Result<Self, SyncRunsError> {
        match member {
            "running" => Ok(SyncRunStatus::Running),
            "success" => Ok(SyncRunStatus::Success),
            "partial" => Ok(SyncRunStatus::Partial),
            "aborted" => Ok(SyncRunStatus::Aborted),
            "failed" => Ok(SyncRunStatus::Failed),
            "interrupted" => Ok(SyncRunStatus::Interrupted),
            _ => Err(SyncRunsError::Member {
                column: "status",
                found: member.to_owned(),
            }),
        }
    }
}

/// The closed `sync_run_projects.status` vocabulary (the §6.2 CHECK):
/// one project's outcome inside one run.
///
/// Phase 0 writes exactly [`SyncRunProjectStatus::NotStarted`] for
/// every row it creates — "this run knows the project, has built its
/// content, and has not touched its file yet"; phase 1's preflight
/// decides `skipped`, phases 3–4 decide `written`/`unchanged`/`failed`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum SyncRunProjectStatus {
    /// The file was written (phase 3).
    Written,
    /// The build matched the existing file (phase 1 step 5).
    Unchanged,
    /// Preflight refused the project (phase 1; `E_PROJECT_UNAVAILABLE`
    /// and its siblings).
    Skipped,
    /// The write failed (phase 3; the row carries the code).
    Failed,
    /// Recorded, content built, file not touched — phase 0's own
    /// value, and the state phase 2's abort resets rows back to.
    NotStarted,
}

impl SyncRunProjectStatus {
    /// Every member, in the §6.2 CHECK's declaration order.
    pub const ALL: [SyncRunProjectStatus; 5] = [
        SyncRunProjectStatus::Written,
        SyncRunProjectStatus::Unchanged,
        SyncRunProjectStatus::Skipped,
        SyncRunProjectStatus::Failed,
        SyncRunProjectStatus::NotStarted,
    ];

    /// The stored TEXT literal (the §6.2 CHECK member).
    pub const fn as_str(&self) -> &'static str {
        match self {
            SyncRunProjectStatus::Written => "written",
            SyncRunProjectStatus::Unchanged => "unchanged",
            SyncRunProjectStatus::Skipped => "skipped",
            SyncRunProjectStatus::Failed => "failed",
            SyncRunProjectStatus::NotStarted => "not_started",
        }
    }

    /// Decodes a stored (or wire) literal — see
    /// [`SyncRunStatus::from_member`] for the one-owner reasoning.
    ///
    /// # Errors
    ///
    /// Returns [`SyncRunsError::Member`] when `member` is none of the
    /// CHECK's literals (D-039).
    pub fn from_member(member: &str) -> Result<Self, SyncRunsError> {
        match member {
            "written" => Ok(SyncRunProjectStatus::Written),
            "unchanged" => Ok(SyncRunProjectStatus::Unchanged),
            "skipped" => Ok(SyncRunProjectStatus::Skipped),
            "failed" => Ok(SyncRunProjectStatus::Failed),
            "not_started" => Ok(SyncRunProjectStatus::NotStarted),
            _ => Err(SyncRunsError::Member {
                column: "status",
                found: member.to_owned(),
            }),
        }
    }
}

// ---- Errors -------------------------------------------------------------------

/// Why a `sync_runs` operation failed.
///
/// Hand-rolled `Display`/`Error` impls, no `thiserror` (the D-093
/// boundary rule this crate keeps); a rusqlite failure lifts into the
/// [`SyncRunsError::Sql`] arm through a `From` impl so `?` composes
/// inside the repositories. `PartialEq` for the tests' exact-value
/// assertions (the decoded vocabulary arms compare by member, not by
/// source error).
#[derive(Debug, PartialEq)]
pub enum SyncRunsError {
    /// A stored cell holds a value outside its closed vocabulary
    /// (`status` of either table). Every writer goes through these
    /// repositories or the schema CHECK, so this means corruption or
    /// a row written by a newer app version; the read surfaces it
    /// instead of guessing (the D-039 corrupt-cells policy).
    Member {
        /// The column the value came from.
        column: &'static str,
        /// The offending value.
        found: String,
    },
    /// The statement or query itself failed — the schema's own CHECK
    /// rejections (a per-project row the `projects` foreign key
    /// refuses; a duplicate project in one run's input hitting the
    /// composite PRIMARY KEY), a closed connection, a tampered schema.
    Sql(rusqlite::Error),
}

impl fmt::Display for SyncRunsError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            SyncRunsError::Member { column, found } => {
                write!(f, "{found:?} is not a valid {column} value")
            }
            SyncRunsError::Sql(err) => write!(f, "database error: {err}"),
        }
    }
}

impl std::error::Error for SyncRunsError {
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        match self {
            SyncRunsError::Sql(err) => Some(err),
            _ => None,
        }
    }
}

/// Lets `?` lift a rusqlite failure into the typed error.
impl From<rusqlite::Error> for SyncRunsError {
    fn from(err: rusqlite::Error) -> Self {
        SyncRunsError::Sql(err)
    }
}

// ---- Row models ---------------------------------------------------------------

/// The columns of a `sync_runs` row, in the fixed order every query
/// of this module selects them in — one list, so the read mapping and
/// the SQL cannot drift apart (the `PROJECT_COLUMNS` pattern).
const SYNC_RUN_COLUMNS: &str = "id, started_at, finished_at, status, \
     projects_total, projects_written, projects_unchanged, \
     projects_skipped, projects_failed, error_code, details";

/// The columns of a `sync_run_projects` row, the same fixed-order
/// contract.
const SYNC_RUN_PROJECT_COLUMNS: &str =
    "sync_run_id, project_id, status, target_path, build_hash, error_code, error_message";

/// A stored `sync_runs` row (§6.2).
///
/// All TEXT columns are stored verbatim; `status` is decoded into the
/// closed vocabulary. The counter columns are the §6.2 defaults
/// (`0`) at phase 0 and stay this module's read-shape only — the
/// phase-4 writer owns their transitions.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SyncRun {
    /// Row id, UUIDv7 TEXT (DB-002), generated by [`create_running`].
    pub id: String,
    /// When the run started, DB-002 UTC ([`crate::values::now_utc`]).
    pub started_at: String,
    /// When the run finished; `None` until phase 4 writes it.
    pub finished_at: Option<String>,
    /// The run's lifecycle status (§6.2 CHECK vocabulary).
    pub status: SyncRunStatus,
    /// How many active projects the run snapshot holds (§9.4 phase 0
    /// knows the count; §6.2's default is only for rows written
    /// without it).
    pub projects_total: i64,
    /// The `written` counter — phase 4's.
    pub projects_written: i64,
    /// The `unchanged` counter — phase 4's.
    pub projects_unchanged: i64,
    /// The `skipped` counter — phase 4's.
    pub projects_skipped: i64,
    /// The `failed` counter — phase 4's.
    pub projects_failed: i64,
    /// The run-level §10 code of a non-success outcome; `None` while
    /// running.
    pub error_code: Option<String>,
    /// Free-text details of the outcome; `None` while running.
    pub details: Option<String>,
}

/// A stored `sync_run_projects` row (§6.2): one project's outcome
/// inside one run.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SyncRunProject {
    /// The owning run's id.
    pub sync_run_id: String,
    /// The project row id (UUIDv7 TEXT, DB-002).
    pub project_id: String,
    /// The project's outcome in this run (§6.2 CHECK vocabulary).
    pub status: SyncRunProjectStatus,
    /// The target file path phase 0 built for (`<root>/<base_name>`
    /// or `<root>/<STEM>.project.md`, §9.4 phase 1 step 2's spelling
    /// before symlink resolution); `None` only in rows written by
    /// phases that had no path to claim.
    pub target_path: Option<String>,
    /// The DB-020 build hash of the content phase 0 assembled — the
    /// same fingerprint DB-024 stores into `projects.
    /// last_synced_hash` after `written`/`unchanged`.
    pub build_hash: Option<String>,
    /// The project-level §10 code of a `skipped`/`failed` outcome.
    pub error_code: Option<String>,
    /// The short error message of a `failed` outcome.
    pub error_message: Option<String>,
}

/// One per-project row of a new run — the input of
/// [`create_running`].
///
/// The status is not an input: a row comes into existence only as
/// `not_started` (§9.4 phase 0's shape), and every later status is a
/// phase-owned transition. `target_path` and `build_hash` are
/// required here because phase 0 has already built them by the time
/// it records the run — a row without them would make phases 1–4
/// rebuild what phase 0 froze, the exact double-build SYS-005's
/// snapshot exists to prevent.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct NewSyncRunProject<'a> {
    /// The project the row is for; must exist (`projects` foreign
    /// key, `ON DELETE RESTRICT`).
    pub project_id: &'a str,
    /// The built target path, stored verbatim (TEXT).
    pub target_path: &'a str,
    /// The DB-020 build hash of the built content, stored verbatim
    /// (TEXT).
    pub build_hash: &'a str,
}

/// The raw cells of one `sync_runs` row — the decode step is fallible
/// on the vocabulary column, and the `query_map` closure must stay
/// infallible (the `ProjectRow`/`LogRow` pattern).
struct SyncRunRow {
    id: String,
    started_at: String,
    finished_at: Option<String>,
    status: String,
    projects_total: i64,
    projects_written: i64,
    projects_unchanged: i64,
    projects_skipped: i64,
    projects_failed: i64,
    error_code: Option<String>,
    details: Option<String>,
}

impl SyncRunRow {
    /// Reads one row in the fixed [`SYNC_RUN_COLUMNS`] order.
    fn from_row(row: &rusqlite::Row<'_>) -> rusqlite::Result<Self> {
        Ok(SyncRunRow {
            id: row.get(0)?,
            started_at: row.get(1)?,
            finished_at: row.get(2)?,
            status: row.get(3)?,
            projects_total: row.get(4)?,
            projects_written: row.get(5)?,
            projects_unchanged: row.get(6)?,
            projects_skipped: row.get(7)?,
            projects_failed: row.get(8)?,
            error_code: row.get(9)?,
            details: row.get(10)?,
        })
    }

    /// Decodes the vocabulary cell and hands back the domain row.
    fn into_sync_run(self) -> Result<SyncRun, SyncRunsError> {
        Ok(SyncRun {
            id: self.id,
            started_at: self.started_at,
            finished_at: self.finished_at,
            status: SyncRunStatus::from_member(&self.status)?,
            projects_total: self.projects_total,
            projects_written: self.projects_written,
            projects_unchanged: self.projects_unchanged,
            projects_skipped: self.projects_skipped,
            projects_failed: self.projects_failed,
            error_code: self.error_code,
            details: self.details,
        })
    }
}

