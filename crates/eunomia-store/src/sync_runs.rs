//! The `sync_runs` / `sync_run_projects` repositories (spec §6.2 DDL,
//! §9.4's pipeline; task T-112).
//!
//! A sync run's database half is two rows-for-one shape: one
//! `sync_runs` row names the run (its id, start time, status, and the
//! per-status counters phase 4 fills), and one `sync_run_projects`
//! row per active project carries that project's outcome through the
//! pipeline (`not_started` at phase 0, then `written` / `unchanged` /
//! `skipped` / `failed` as phases 1–4 decide). This module is the
//! store's writer for the **phase-0 shape only** — the `running` run
//! with its `not_started` rows — plus the reads the later phases and
//! the history UI will consume. The status *transitions* (running →
//! success/partial/aborted/failed/interrupted, per-project
//! not_started → its outcome) belong to the phase tasks that cause
//! them (T-113+), exactly the way `projects.rs` leaves
//! `last_synced_at`/`last_synced_hash` to the sync tasks (OUT-020):
//! a repository owns the shape of a row, the pipeline owns when the
//! world is ready to claim it.
//!
//! # One transaction, joined — not owned
//!
//! Like every repository function (D-037/D-051), [`create_running`]
//! takes `&Connection` and joins **the caller's** transaction: the
//! run row and its per-project rows commit or vanish as one set only
//! because the app-layer executor wraps the call in one transaction
//! (`Db::run(|tx| sync_runs::create_running(tx, …))`). Called bare
//! in autocommit, the statements would commit one by one — the
//! module docs of [`crate::build_snapshot`] spell out the same
//! calling contract for its read; the integration suite pins the
//! wrapped shape (a per-project row that cannot insert rolls the run
//! row back with it, leaving zero rows).
//!
//! # What phase 0 records, and what it defers
//!
//! §9.4 phase 0 step 2: "Create a `sync_runs` record with the
//! `running` status, record the start time and the snapshot
//! (ALG-001), and build the content for all active projects." The
//! snapshot itself is not a column — it lives in the run's
//! *consequences*: every per-project row carries the target path and
//! the DB-020 build hash of the content phase 0 built, so phases 1–4
//! and the DB-024 writer (`projects.last_synced_hash` after
//! `written`/`unchanged`) read the run's fingerprint instead of
//! rebuilding it. The counters stay 0 and `finished_at`/`error_code`
//! stay NULL: phase 4 owns them, and the crash-recovery rule
//! ("`running` records get `interrupted` at startup") reads their
//! absence as the honest phase-0 state.
//!
//! # Ids and times
//!
//! The id is a UUIDv7 in canonical lowercase TEXT
//! ([`crate::values::new_id`], DB-002), generated by
//! [`create_running`] *inside* the joined transaction — a rolled-back
//! attempt leaves nothing behind, and a busy-retried one (the
//! `Db::run` cycle) draws a fresh id on its fresh attempt. The
//! `started_at` timestamp is the **caller's** run-start value (the
//! app layer captures it when the run takes its flag, §9.4's
//! "record the start time" — see [`create_running`]); it must be the
//! DB-002 UTC millisecond shape ([`crate::values::now_utc`]).
//!
//! # Retention is already wired — not here
//!
//! §6.4's "the last 500 runs" is enforced by
//! [`crate::action_log::cleanup`] (T-029), which prunes `sync_runs`
//! past [`crate::action_log::SYNC_RUNS_KEPT`] and cascades into
//! `sync_run_projects` (the `ON DELETE CASCADE` this DDL gives the
//! link table). This module adds no cleanup of its own and must not:
//! one owner per policy.

